export const REFERENCE_DATE = '2026-10-23';

/**
 * Returns formatted ISO date (YYYY-MM-DD) offset by days from the reference date.
 */
export function getOffsetDateString(days: number, fromDate: string = REFERENCE_DATE): string {
  const date = new Date(fromDate);
  date.setDate(date.getDate() + days);
  return date.toISOString().split('T')[0];
}

